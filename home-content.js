/**
 * Return a frame URL.
 */
export function getFrameURL(index) {

  const {
    folder,
    filenamePrefix,
    extension,
    digits
  } = HOME_CONTENT.frames;

  return (
    folder +
    filenamePrefix +
    String(index).padStart(digits, "0") +
    extension
  );

}


/**
 * Return event by ID.
 */
export function getEvent(eventId) {

  return HOME_CONTENT.battle.events.find(
    event => event.id === eventId
  );

}


/**
 * Check whether the registration deadline has passed.
 */
export function isRegistrationClosed() {

  return Date.now() >=
    new Date(
      HOME_CONTENT.event.registrationDeadlineISO
    ).getTime();

}


/**
 * Return remaining registration time.
 */
export function getRegistrationTimeLeft() {

  const deadline =
    new Date(
      HOME_CONTENT.event.registrationDeadlineISO
    ).getTime();

  const difference =
    deadline - Date.now();

  if (difference <= 0) {

    return {
      expired: true,
      days: 0,
      hours: 0,
      minutes: 0,
      seconds: 0
    };

  }


  const days =
    Math.floor(
      difference /
      (1000 * 60 * 60 * 24)
    );


  const hours =
    Math.floor(
      (difference /
        (1000 * 60 * 60)) %
      24
    );


  const minutes =
    Math.floor(
      (difference /
        (1000 * 60)) %
      60
    );


  const seconds =
    Math.floor(
      (difference /
        1000) %
      60
    );


  return {

    expired: false,

    days,

    hours,

    minutes,

    seconds

  };

}


/**
 * Two-digit number helper.
 */
export function twoDigits(value) {

  return String(value)
    .padStart(2, "0");

}
